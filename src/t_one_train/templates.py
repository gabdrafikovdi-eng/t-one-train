TRAIN = [
    "{nom}", "на {pre}", "до {gen}", "{bare}", "на {at}",
    "мне на {acc}", "я на {pre}", "едем на {acc}",
    "заберите меня на {pre}", "мне машину на {acc}",
    "заберите меня пожалуйста на {pre}", "я нахожусь на {pre}",
    "мне нужно на {acc}", "поедем на {acc}",
    "мне нужна машина до {gen}", "я сейчас нахожусь на {pre}",
    "я жду такси на {pre}", "закажите мне такси на {acc}",
    "можно машину на {acc}", "можно доехать до {gen}",
    "отвезите меня на {acc}", "подъезжайте к началу {gen}",
    "я буду ждать на {pre}", "пожалуйста отправьте такси на {acc}",
    "хочу заказать машину на {acc}", "мне надо добраться до {gen}",
    "ждём машину на {pre}", "нам нужно такси на {acc}",
    "заберёте нас на {pre}", "мы стоим на {pre}",
    "можете забрать меня на {pre}", "вызываю машину на {acc}",
    "нужна поездка до {gen}", "хотел бы уехать с {gen}",
    "хотела бы уехать с {gen}", "вызовите пожалуйста такси на {acc}",
    "водитель сможет подъехать на {acc}", "нужно забрать пассажира на {pre}",
    "мне пожалуйста до {gen}", "машина нужна на {acc}",
    "сколько ждать машину на {pre}", "я уже вышел на {acc}",
    "я уже вышла на {acc}", "мы с ребёнком на {pre}",
    "я с сумками на {pre}", "пожалуйста отвезите нас до {gen}",
    "можно заказать поездку до {gen}", "хочу уехать на {acc}",
    "такси ждём возле начала {gen}", "мне бы машину до {gen}",
]
VALIDATION = [
    "уточняю место посадки это {nom}",
    "передайте водителю что я на {pre}",
    "куда подъехать адрес такой {nom}",
    "сможете прислать свободную машину на {acc}",
    "встречайте меня пожалуйста на {pre}",
    "посадка будет на {pre}",
    "скажите водителю заехать на {acc}",
    "адрес откуда меня забрать это {nom}",
]
TEST = [
    "машину нужно подать на {acc}",
    "точка подачи такси это {nom}",
    "отправной точкой будет {nom}",
    "поездка начнётся на {pre}",
    "водителю надо остановиться на {pre}",
    "запишите конечный адрес это {nom}",
    "меня следует подобрать на {pre}",
    "для посадки подъедьте пожалуйста на {acc}",
    "таксисту нужно приехать к началу {gen}",
    "местом встречи с водителем будет {nom}",
]
PREFIXES = ["", "алло", "здравствуйте", "добрый день", "добрый вечер", "слушайте"]
TAILS = [
    "", "пожалуйста", "я уже на месте", "я выйду к дороге",
    "буду ждать у ворот", "подожду возле дома", "я буду с сумкой",
    "нас будет двое", "поеду один", "поеду одна", "я с ребёнком",
    "у меня небольшой багаж", "позвоните когда подъедете",
    "я выйду как только позвоните", "сдача понадобится",
    "оплачу наличными", "можно оплатить картой", "долго ждать машину",
    "я тороплюсь", "встретим водителя у входа",
]
BANKS = {"train": TRAIN, "validation": VALIDATION, "test": TEST}


def candidates(split):
    for i, base in enumerate(BANKS[split]):
        # Very short utterances remain short; context gets meaningful combinations.
        prefixes = PREFIXES if len(base.split()) > 2 else [""]
        tails = TAILS if len(base.split()) > 2 else [""]
        for prefix in prefixes:
            for tail in tails:
                if "пожалуйста" in base and tail == "пожалуйста":
                    continue
                # Avoid explicit contradictory singular/gender combinations.
                if tail in ("поеду один", "поеду одна", "нас будет двое"):
                    if any(w in base.split() for w in ("вышел", "вышла", "нас", "мы", "нам", "ждём")):
                        continue
                yield ", ".join(x for x in (prefix, base, tail) if x), f"{split}:{i}"
