"""Interactive manual recorder for the real-world evaluation dataset.

- ENTER-driven recording only (no VAD, no automatic start/stop).
- Playback after each take; save / re-record / edit reference / skip menu.
- Audio captured at native mic rate, resampled to 8 kHz mono PCM16 on save;
  no noise/codec/gain augmentation.
- FULL reference is the verbatim streets.txt line (type words are never added
  and the name is never declined).
- SHORT (e.g. "Хисматуллина") and NATURAL (e.g. "До Абзелиловской") references
  are NOT generated by the program: the user types them before recording, and
  ENTER / "-" at the prompt skips that record (status="skipped", no audio).
  So the reference always matches the phrase actually spoken.
- Resume: records already in manifest.jsonl (saved or skipped) are skipped;
  recording continues from the first missing record.

Usage:
    uv run python scripts/record_real_dataset.py            # resume latest / create new
    uv run python scripts/record_real_dataset.py --new      # force a new dataset
    uv run python scripts/record_real_dataset.py --dataset results/real_dataset_XXX/
    uv run python scripts/record_real_dataset.py --limit 2  # smoke: first 2 streets only
"""

